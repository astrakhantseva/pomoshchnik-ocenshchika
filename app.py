def _crs_имя_из_словаря(словарь):
    """Достаёт имя системы координат из GeoJSON-объекта или пустую строку."""
    if not isinstance(словарь, dict):
        return ""
    crs = словарь.get("crs")
    if not isinstance(crs, dict):
        return ""
    свойства = crs.get("properties")
    if not isinstance(свойства, dict):
        return ""
    return str(свойства.get("name") or "")


def _точки_кольца(кольцо):
    """Превращает кольцо координат в список пар чисел, отбрасывая мусор."""
    if not isinstance(кольцо, (list, tuple)):
        return []
    точки = []
    for точка in кольцо:
        if not isinstance(точка, (list, tuple)) or len(точка) < 2:
            continue
        x = в_число(точка[0])
        y = в_число(точка[1])
        if x is None or y is None:
            continue
        точки.append((x, y))
    # В GeoJSON последняя точка повторяет первую — для площади она не нужна.
    if len(точки) > 1 and точки[0] == точки[-1]:
        точки = точки[:-1]
    return точки


def _площадь_кольца(кольцо):
    """Площадь кольца в единицах исходных координат (для выбора крупного)."""
    точки = _точки_кольца(кольцо)
    if len(точки) < 3:
        return 0.0
    площадь2 = 0.0
    for номер in range(len(точки)):
        x1, y1 = точки[номер]
        x2, y2 = точки[(номер + 1) % len(точки)]
        площадь2 += x1 * y2 - x2 * y1
    return abs(площадь2) / 2.0


def _центр_кольца(кольцо):
    """Центр полигонального кольца; для вырожденного кольца — среднее точек."""
    точки = _точки_кольца(кольцо)
    if not точки:
        return None
    if len(точки) < 3:
        return (
            sum(x for x, _ in точки) / len(точки),
            sum(y for _, y in точки) / len(точки),
        )

    площадь2 = 0.0
    центр_x = 0.0
    центр_y = 0.0
    for номер in range(len(точки)):
        x1, y1 = точки[номер]
        x2, y2 = точки[(номер + 1) % len(точки)]
        cross = x1 * y2 - x2 * y1
        площадь2 += cross
        центр_x += (x1 + x2) * cross
        центр_y += (y1 + y2) * cross

    if abs(площадь2) < 1e-9:
        return (
            sum(x for x, _ in точки) / len(точки),
            sum(y for _, y in точки) / len(точки),
        )

    площадь2 *= 0.5
    return центр_x / (6.0 * площадь2), центр_y / (6.0 * площадь2)


def перевод_3857_в_широту_долготу(x, y):
    """
    Переводит координаты EPSG:3857 (Web Mercator) в широту и долготу.

    Возвращает пару (широта, долгота) в градусах либо None, если координаты
    не числа или выходят за допустимые пределы.
    """
    x = в_число(x)
    y = в_число(y)
    if x is None or y is None or not math.isfinite(x) or not math.isfinite(y):
        return None

    радиус = 6378137.0
    try:
        долгота = x / радиус * 180.0 / math.pi
        широта = (
            2.0 * math.atan(math.exp(y / радиус)) - math.pi / 2.0
        ) * 180.0 / math.pi
    except (OverflowError, ValueError):
        return None

    if not (-90.0 <= широта <= 90.0) or not (-180.0 <= долгота <= 180.0):
        return None
    return широта, долгота


def центр_геометрии(geometry, crs_имя=None):
    """
    Возвращает центр GeoJSON-геометрии в виде (широта, долгота) или None.

    Поддерживаются Point, Polygon и MultiPolygon. Для полигона берётся
    внешнее кольцо, для MultiPolygon — самый крупный полигон. Координаты
    EPSG:3857 переводятся в градусы, готовые широта и долгота остаются как есть.
    """
    if isinstance(geometry, str):
        try:
            geometry = json.loads(geometry)
        except (TypeError, ValueError):
            return None
    if not isinstance(geometry, dict):
        return None

    тип = str(geometry.get("type") or "").strip().lower()
    координаты = geometry.get("coordinates")
    if not координаты:
        return None

    if тип == "point":
        if not isinstance(координаты, (list, tuple)) or len(координаты) < 2:
            return None
        центр_x = в_число(координаты[0])
        центр_y = в_число(координаты[1])
        if центр_x is None or центр_y is None:
            return None

    elif тип == "polygon":
        if not isinstance(координаты, (list, tuple)) or not координаты:
            return None
        центр = _центр_кольца(координаты[0])
        if центр is None:
            return None
        центр_x, центр_y = центр

    elif тип == "multipolygon":
        if not isinstance(координаты, (list, tuple)):
            return None
        лучший_центр = None
        лучшая_площадь = -1.0
        for полигон in координаты:
            if not isinstance(полигон, (list, tuple)) or not полигон:
                continue
            центр = _центр_кольца(полигон[0])
            if центр is None:
                continue
            площадь = _площадь_кольца(полигон[0])
            if площадь > лучшая_площадь:
                лучшая_площадь = площадь
                лучший_центр = центр
        if лучший_центр is None:
            return None
        центр_x, центр_y = лучший_центр

    else:
        return None

    имя = str(crs_имя or _crs_имя_из_словаря(geometry)).lower()
    if "3857" in имя or "900913" in имя or "mercator" in имя:
        проекция = True
    elif "4326" in имя or "crs84" in имя or "wgs" in имя:
        проекция = False
    else:
        # Без явной системы координат: метры заметно больше градусов.
        проекция = abs(центр_x) > 180.0 or abs(центр_y) > 90.0

    if проекция:
        return перевод_3857_в_широту_долготу(центр_x, центр_y)

    широта, долгота = центр_y, центр_x
    if not (-90.0 <= широта <= 90.0) or not (-180.0 <= долгота <= 180.0):
        return None
    return широта, долгота


def координаты_объекта(объект):
    """Возвращает координаты объекта НСПД словарём или None."""
    if not isinstance(объект, dict):
        return None
    геометрия = объект.get("geometry")
    if not геометрия:
        return None

    центр = центр_геометрии(геометрия, _crs_имя_из_словаря(объект))
    if центр is None:
        return None
    return {"широта": центр[0], "долгота": центр[1]}


def координаты_объявления(объявление):
    """Возвращает координаты точки объявления словарём или None."""
    if not isinstance(объявление, dict):
        return None
    место = объявление.get("location")
    if not isinstance(место, dict):
        return None
    точка = место.get("point")
    if not isinstance(точка, dict):
        return None

    широта = в_число(точка.get("latitude"))
    долгота = в_число(точка.get("longitude"))
    if широта is None or долгота is None:
        return None
    if not (-90.0 <= широта <= 90.0) or not (-180.0 <= долгота <= 180.0):
        return None
    return {"широта": широта, "долгота": долгота}


def расстояние_км(широта1, долгота1, широта2, долгота2):
    """
    Расстояние между двумя точками по формуле гаверсинуса в километрах.

    Возвращает число или None, если координаты не числа или не в градусах.
    """
    широта1 = в_число(широта1)
    долгота1 = в_число(долгота1)
    широта2 = в_число(широта2)
    долгота2 = в_число(долгота2)
    if None in (широта1, долгота1, широта2, долгота2):
        return None
    if not (-90.0 <= широта1 <= 90.0) or not (-90.0 <= широта2 <= 90.0):
        return None
    if not (-180.0 <= долгота1 <= 180.0) or not (-180.0 <= долгота2 <= 180.0):
        return None

    фи1 = math.radians(широта1)
    фи2 = math.radians(широта2)
    дельта_фи = фи2 - фи1
    дельта_лямбда = math.radians(долгота2 - долгота1)

    a = (
        math.sin(дельта_фи / 2.0) ** 2
        + math.cos(фи1) * math.cos(фи2) * math.sin(дельта_лямбда / 2.0) ** 2
    )
    a = min(1.0, max(0.0, a))
    return 2.0 * 6371.0088 * math.asin(math.sqrt(a))


def _подпись_цены_за_метр(значение):
    """Цена за кв. м для подписи на карте: целые рубли с пробелами."""
    число = в_число(значение)
    if число is None or not math.isfinite(число):
        return "—"
    return f"{round(число):,}".replace(",", " ")


def _адрес_для_подсказки(адрес):
    """Экранирует адрес и переносит строку после запятых, чтобы он читался."""
    текст = html.escape(str(адрес or "адрес не указан"))
    return текст.replace(", ", ",<br>")


def _точка_для_карты(широта, долгота):
    """Проверяет пару координат и возвращает её словарём или None."""
    широта = в_число(широта)
    долгота = в_число(долгота)
    if (широта is None or долгота is None
            or not math.isfinite(широта) or not math.isfinite(долгота)):
        return None
    if not (-90.0 <= широта <= 90.0) or not (-180.0 <= долгота <= 180.0):
        return None
    return {"широта": широта, "долгота": долгота}


def _точки_круга(широта, долгота, радиус_км, точек=72):
    """
    Возвращает широты и долготы замкнутой линии круга вокруг точки.

    Радиус в один километр мал по сравнению с Землёй, поэтому смещение
    считаем в градусах: по широте — прямо, по долготе — с поправкой на то,
    что параллели к полюсам короче.
    """
    угловой_радиус = радиус_км / 6371.0088
    широта_рад = math.radians(широта)
    косинус_широты = math.cos(широта_рад)
    # У самого полюса параллель вырождается в точку — не делим на ноль.
    if abs(косинус_широты) < 1e-6:
        косинус_широты = 1e-6 if косинус_широты >= 0 else -1e-6

    широты = []
    долготы = []
    for номер in range(точек + 1):
        угол = 2.0 * math.pi * номер / точек
        широта_точки = широта_рад + угловой_радиус * math.cos(угол)
        долгота_точки = (
            math.radians(долгота)
            + угловой_радиус * math.sin(угол) / косинус_широты
        )
        широты.append(math.degrees(широта_точки))
        долготы.append(
            (math.degrees(долгота_точки) + 180.0) % 360.0 - 180.0
        )
    return широты, долготы


def построить_карту(объект, аналоги, включённые_ссылки, средняя_за_метр=None):
    """
    Собирает фигуру Plotly с объектом и аналогами.

    Аналоги, включённые в расчёт, раскрашены по цене квадратного метра
    относительно средней цены по этим же аналогам: дешевле средней — зелёные,
    дороже — оранжевые. Исключённые из расчёта остаются серыми, объект красный.
    Вокруг объекта, если у него есть координаты, рисуется круг радиусом 1 км.

    Возвращает пару (фигура, сведения). Фигура равна None, если ни у одного
    аналога нет координат: в этом случае карту строить не из чего.
    Сведения — словарь со счётчиками и списком аналогов без координат.
    """
    объект = объект or {}
    аналоги = аналоги or []
    включённые_ссылки = set(включённые_ссылки or [])

    координаты_объекта = объект.get("_координаты")
    точка_объекта = None
    if isinstance(координаты_объекта, dict):
        точка_объекта = _точка_для_карты(
            координаты_объекта.get("широта"),
            координаты_объекта.get("долгота"),
        )

    точки_аналогов = []
    без_координат = []
    for аналог in аналоги:
        if not isinstance(аналог, dict):
            без_координат.append(аналог)
            continue

        точка = _точка_для_карты(аналог.get("Широта"), аналог.get("Долгота"))
        if точка is None:
            без_координат.append(аналог)
            continue

        точки_аналогов.append({
            "аналог": аналог,
            "широта": точка["широта"],
            "долгота": точка["долгота"],
            "в_расчёте": аналог.get("Ссылка") in включённые_ссылки,
            "цена_за_метр": в_число(аналог.get("Цена за кв. м, руб.")),
        })

    сведения = {
        "всего": len(аналоги),
        "с_координатами": len(точки_аналогов),
        "без_координат": без_координат,
        "объект_без_координат": точка_объекта is None,
    }

    if not точки_аналогов:
        return None, сведения

    фигура = go.Figure()

    # Круг радиуса 1 км рисуем первым, чтобы точки аналогов были поверх него.
    # Если координат объекта нет, круга на карте тоже нет.
    круг_объекта = None
    if точка_объекта:
        круг_широты, круг_долготы = _точки_круга(
            точка_объекта["широта"], точка_объекта["долгота"], 1.0
        )
        круг_объекта = (круг_широты, круг_долготы)
        фигура.add_trace(go.Scattermap(
            lat=круг_широты,
            lon=круг_долготы,
            mode="lines",
            fill="toself",
            fillcolor="rgba(229,57,53,0.05)",
            line=dict(width=1, color="#E53935"),
            name="1 км от объекта",
            hoverinfo="skip",
            showlegend=True,
        ))

    if точка_объекта:
        адрес_объекта = _адрес_для_подсказки(
            объект.get("readable_address")
        )
        номер_объекта = html.escape(
            str(первое_заполненное(объект, "cad_num", "cad_number") or "—")
        )
        фигура.add_trace(go.Scattermap(
            lat=[точка_объекта["широта"]],
            lon=[точка_объекта["долгота"]],
            mode="markers+text",
            marker=dict(size=16, color="#E53935"),
            text=["Объект"],
            textposition="top center",
            textfont=dict(size=16, color="#E53935"),
            name="Объект",
            hovertext=[
                f"<b>Объект</b><br>{адрес_объекта}"
                f"<br>Кадастровый номер: {номер_объекта}"
            ],
            hoverinfo="text",
            hovertemplate="%{hovertext}<extra></extra>",
            showlegend=True,
        ))

    средняя = в_число(средняя_за_метр)
    if средняя is None or not math.isfinite(средняя):
        средняя = None

    дешевле = []
    дороже = []
    без_сравнения = []
    не_в_расчёте = []
    for точка in точки_аналогов:
        цена = точка["цена_за_метр"]
        if not точка["в_расчёте"]:
            не_в_расчёте.append(точка)
        elif (средняя is None or цена is None
                or not math.isfinite(цена)):
            # Цену сравнить не с чем: точку не красим ни в «дешевле»,
            # ни в «дороже», но из расчёта она не выпадает.
            без_сравнения.append(точка)
        elif цена < средняя:
            дешевле.append(точка)
        else:
            дороже.append(точка)

    группы = (
        (дешевле, "Дешевле средней цены за кв. м", "#2E7D32", "#1B5E20"),
        (дороже, "Дороже средней цены за кв. м", "#EF6C00", "#BF360C"),
        (
            без_сравнения,
            "В расчёте, цену сравнить нельзя",
            "#BDBDBD",
            "#616161",
        ),
        (не_в_расчёте, "Не в расчёте", "#9E9E9E", "#757575"),
    )

    for точки, название, цвет_точки, цвет_подписи in группы:
        if not точки:
            continue

        подписи = []
        подсказки = []
        for точка in точки:
            аналог = точка["аналог"]
            подписи.append(_подпись_цены_за_метр(аналог.get("Цена за кв. м, руб.")))

            строки = [
                "<b>Аналог</b> "
                f"({'в расчёте' if точка['в_расчёте'] else 'не в расчёте'})",
                _адрес_для_подсказки(аналог.get("Адрес")),
                f"Цена: {красиво_число(аналог.get('Цена, руб.'), 'руб.')}",
                f"Площадь: {красиво_число(аналог.get('Площадь, кв. м'), 'кв. м')}",
                "Цена за кв. м: "
                + красиво_число(аналог.get("Цена за кв. м, руб."), "руб."),
            ]
            if точка_объекта:
                км = расстояние_км(
                    точка_объекта["широта"],
                    точка_объекта["долгота"],
                    точка["широта"],
                    точка["долгота"],
                )
                if км is not None:
                    строки.append(
                        f"Расстояние: {км:.1f} км".replace(".", ",")
                    )
            подсказки.append("<br>".join(строки))

        фигура.add_trace(go.Scattermap(
            lat=[т["широта"] for т in точки],
            lon=[т["долгота"] for т in точки],
            mode="markers+text",
            marker=dict(size=10, color=цвет_точки),
            text=подписи,
            textposition="bottom center",
            textfont=dict(size=14, color=цвет_подписи),
            name=название,
            hovertext=подсказки,
            hoverinfo="text",
            hovertemplate="%{hovertext}<extra></extra>",
            showlegend=True,
        ))

    все_точки = []
    if точка_объекта:
        все_точки.append((точка_объекта["широта"], точка_объекта["долгота"]))
    # Край круга тоже должен попасть в кадр, иначе при близких аналогах
    # карта приблизится настолько, что круг обрежется по краям.
    if круг_объекта:
        все_точки.extend(zip(круг_объекта[0], круг_объекта[1]))
    все_точки.extend((т["широта"], т["долгота"]) for т in точки_аналогов)

    широты = [точка[0] for точка in все_точки]
    долготы = [точка[1] for точка in все_точки]
    центр_широта = (min(широты) + max(широты)) / 2.0
    центр_долгота = (min(долготы) + max(долготы)) / 2.0

    # Запас 25 % по размаху — примерно по 12,5 % с каждой стороны.
    размах_широт = (max(широты) - min(широты)) * 1.25
    размах_долгот = (max(долготы) - min(долготы)) * 1.25

    ширина_карты, высота_карты = 1000.0, 420.0
    масштабы = []
    if размах_широт > 0:
        # В проекции Меркатора один градус широты занимает на экране
        # больше места, чем на экваторе, поэтому учитываем cos(широты).
        # Без этого карта открывается слишком близко и крайние точки
        # остаются за кадром.
        масштабы.append(math.log2(
            360.0 * высота_карты * math.cos(math.radians(центр_широта))
            / (512.0 * размах_широт)
        ))
    if размах_долгот > 0:
        # 512 — размер мирового тайла в MapLibre, которым Plotly рисует
        # карту. Если считать по 256, карта открывается на уровень ближе
        # и крайние точки по долготе могут остаться за кадром.
        масштабы.append(math.log2(
            360.0 * ширина_карты / (512.0 * размах_долгот)
        ))
    масштаб = min(масштабы) if масштабы else 15.0
    масштаб = max(3.0, min(16.0, масштаб))

    фигура.update_layout(
        map=dict(
            style="open-street-map",
            center=dict(lat=центр_широта, lon=центр_долгота),
            zoom=масштаб,
        ),
        margin=dict(l=0, r=0, t=0, b=0),
        height=420,
        legend=dict(
            x=0.01,
            y=0.99,
            xanchor="left",
            yanchor="top",
            bgcolor="rgba(255,255,255,0.8)",
        ),
        showlegend=True,
    )

    return фигура, сведения


# ───────────────────────── Запрос объекта в Росреестре ───────────────────────

def запросить_объект(кадастровый_номер):
    """
    Делает живой запрос к геопорталу НСПД и возвращает характеристики объекта,
    чей кадастровый номер ТОЧНО совпал с введённым.

    Возвращает словарь с полями объекта либо None, если такого объекта нет.
    """
    if учебный_набор:
        # Учебный набор: ответ НСПД о вымышленном объекте лежит в файле.
        файл = ПАПКА_УЧЕБНОГО_НАБОРА / "nspd_obekt.json"
        данные = json.loads(файл.read_text(encoding="utf-8"))
    else:
        ответ = cffi.get(
            API_URL,
            params={
                "query": кадастровый_номер,
                "thematicSearchId": THEMATIC_SEARCH_ID,
            },
            headers=HEADERS,
            impersonate="chrome",  # притворяемся настоящим Chrome на уровне TLS
            verify=False,          # не проверяем российский сертификат сайта
            timeout=30,
        )

        # 404 у этого сервиса означает «ничего не нашлось» — это не поломка.
        if ответ.status_code == 404:
            return None

        if ответ.status_code != 200:
            raise ОшибкаСервера(
                f"Геопортал ответил кодом {ответ.status_code}. "
                "Попробуйте повторить запрос через минуту."
            )

        try:
            данные = ответ.json()
        except Exception:
            raise ОшибкаСервера(
                "Геопортал вернул ответ, который не удалось прочитать. "
                "Попробуйте повторить запрос через минуту."
            )

    # Объекты лежат в data.features. Если ничего не нашлось, data может быть
    # пустой (null) — конструкция «or {}» защищает от ошибки в этом случае.
    features = ((данные or {}).get("data") or {}).get("features") or []

    искомый = очистить_номер(кадастровый_номер)

    # Сервис умеет отвечать «похожими» объектами, поэтому берём только тот,
    # чей номер совпал с введённым буква в букву.
    # Само поле с номером у НСПД называется по-разному: у участков и зданий —
    # cad_num, у помещений — cad_number. Проверяем оба.
    for объект in features:
        поля = ((объект or {}).get("properties") or {}).get("options") or {}
        номер_объекта = первое_заполненное(поля, "cad_num", "cad_number")
        if очистить_номер(номер_объекта) == искомый:
            # Служебный ключ с координатами нужен только карте. Копируем
            # поля, чтобы не менять исходный ответ НСПД, и возвращаем копию.
            поля = dict(поля)
            поля["_координаты"] = координаты_объекта(объект)
            return поля

    return None


# ──────────────── Разбор адреса объекта: город, улица, сегмент ───────────────

def определить_город(адрес):
    """
    Ищет в адресе объекта название города из справочника ГОРОДА.

    Возвращает пару (как город назван в адресе, как он назван на сайте)
    либо (None, None), если подходящего города в справочнике нет.

    Ищем не простым вхождением, а по границам слова (\\b в шаблоне поиска).
    Иначе, например, «Омск» нашёлся бы внутри слова «Томск», «Пенза» — внутри
    «Пензенская», а «Москва» — внутри «Московская». Границы слова этого
    не допускают.
    """
    текст = (адрес or "").lower()
    for город, город_на_сайте in ГОРОДА.items():
        шаблон = r"\b" + re.escape(город) + r"\b"
        if re.search(шаблон, текст):
            return город, город_на_сайте
    return None, None


def определить_сегмент(назначение):
    """
    Подбирает сегмент поиска по назначению объекта из Росреестра.
    Возвращает название сегмента либо None, если назначение не распознано.

    Порядок проверок важен: слово «нежилое» содержит внутри себя «жилое»,
    поэтому нежилые назначения проверяем раньше жилых. По той же причине
    индивидуальный жилой дом проверяется самым первым.
    """
    текст = (назначение or "").lower()

    if "индивидуальн" in текст and ("жилой дом" in текст or "жилищн" in текст):
        return "Дома"
    if "торгов" in текст:
        return "Торговые помещения"
    if any(слово in текст for слово in ("офис", "контор", "административ", "нежил")):
        return "Офисы"
    # «Многоквартирный дом» — тоже жилое назначение, но слова «жилой» в нём нет.
    if "жил" in текст or "многоквартирн" in текст:
        return "Квартиры"
    return None


def _слова(текст):
    """
    Режет кусок адреса на слова и снимает точки, кавычки и запятые по краям.
    Дефис внутри слова сохраняем — иначе развалятся сокращения вроде «пр-кт».
    """
    текст = (текст or "").lower().replace("ё", "е")
    мусор = ".,;:«»\"'()"
    слова = [слово.strip(мусор) for слово in текст.split()]
    return [слово for слово in слова if слово]


def выделить_улицу(адрес):
    """
    Достаёт из адреса название улицы и приводит его к виду, пригодному
    для сравнения: набор слов без слова «улица», «проспект» и им подобных.

    Возвращает набор слов (например {"советской", "армии"}) либо None,
    если в адресе улицу распознать не удалось.

    Почему набор, а не строка: так порядок слов перестаёт иметь значение,
    и «улица Советской Армии» совпадёт с «Советской Армии улица».
    """
    for часть in (адрес or "").split(","):
        слова = _слова(часть)
        # Часть адреса считаем улицей, если в ней есть слово-тип улицы.
        if not any(слово in СЛОВА_ТИПОВ_УЛИЦ for слово in слова):
            continue
        название = [слово for слово in слова if слово not in СЛОВА_ТИПОВ_УЛИЦ]
        if название:
            return frozenset(название)
    return None


