def запросить_объект(кадастровый_номер):
    """
    Делает живой запрос к геопорталу НСПД и возвращает характеристики объекта,
    чей кадастровый номер ТОЧНО совпал с введённым.

    Возвращает словарь с полями объекта либо None, если такого объекта нет.
    """
    ответ = cffi.get(
        API_URL,
        params={
            "query": кадастровый_номер,
            "thematicSearchId": THEMATIC_SEARCH_ID,
        },
        headers=HEADERS,
        impersonate="chrome",  # притворяемся настоящим Chrome на уровне TLS
        verify=False,          # не проверяем российский сертификат сайта
        timeout=30,
    )

    # 404 у этого сервиса означает «ничего не нашлось» — это не поломка.
    if ответ.status_code == 404:
        return None

    if ответ.status_code != 200:
        raise ОшибкаСервера(
            f"Геопортал ответил кодом {ответ.status_code}. "
            "Попробуйте повторить запрос через минуту."
        )

    try:
        данные = ответ.json()
    except Exception:
        raise ОшибкаСервера(
            "Геопортал вернул ответ, который не удалось прочитать. "
            "Попробуйте повторить запрос через минуту."
        )

    # Объекты лежат в data.features. Если ничего не нашлось, data может быть
    # пустой (null) — конструкция «or {}» защищает от ошибки в этом случае.
    features = ((данные or {}).get("data") or {}).get("features") or []

    искомый = очистить_номер(кадастровый_номер)

    # Сервис умеет отвечать «похожими» объектами, поэтому берём только тот,
    # чей номер совпал с введённым буква в букву.
    # Само поле с номером у НСПД называется по-разному: у участков и зданий —
    # cad_num, у помещений — cad_number. Проверяем оба.
    for объект in features:
        поля = ((объект or {}).get("properties") or {}).get("options") or {}
        номер_объекта = первое_заполненное(поля, "cad_num", "cad_number")
        if очистить_номер(номер_объекта) == искомый:
            return поля

    return None


# ──────────────── Разбор адреса объекта: город, улица, сегмент ───────────────

def определить_город(адрес):
    """
    Ищет в адресе объекта название города из справочника ГОРОДА.

    Возвращает пару (как город назван в адресе, как он назван на сайте)
    либо (None, None), если подходящего города в справочнике нет.

    Ищем не простым вхождением, а по границам слова (\\b в шаблоне поиска).
    Иначе, например, «Омск» нашёлся бы внутри слова «Томск», «Пенза» — внутри
    «Пензенская», а «Москва» — внутри «Московская». Границы слова этого
    не допускают.
    """
    текст = (адрес or "").lower()
    for город, город_на_сайте in ГОРОДА.items():
        шаблон = r"\b" + re.escape(город) + r"\b"
        if re.search(шаблон, текст):
            return город, город_на_сайте
    return None, None


def определить_сегмент(назначение):
    """
    Подбирает сегмент поиска по назначению объекта из Росреестра.
    Возвращает название сегмента либо None, если назначение не распознано.

    Порядок проверок важен: слово «нежилое» содержит внутри себя «жилое»,
    поэтому нежилые назначения проверяем раньше жилых. По той же причине
    индивидуальный жилой дом проверяется самым первым.
    """
    текст = (назначение or "").lower()

    if "индивидуальн" in текст and ("жилой дом" in текст or "жилищн" in текст):
        return "Дома"
    if "торгов" in текст:
        return "Торговые помещения"
    if any(слово in текст for слово in ("офис", "контор", "административ", "нежил")):
        return "Офисы"
    # «Многоквартирный дом» — тоже жилое назначение, но слова «жилой» в нём нет.
    if "жил" in текст or "многоквартирн" in текст:
        return "Квартиры"
    return None


def _слова(текст):
    """
    Режет кусок адреса на слова и снимает точки, кавычки и запятые по краям.
    Дефис внутри слова сохраняем — иначе развалятся сокращения вроде «пр-кт».
    """
    текст = (текст or "").lower().replace("ё", "е")
    мусор = ".,;:«»\"'()"
    слова = [слово.strip(мусор) for слово in текст.split()]
    return [слово for слово in слова if слово]


def выделить_улицу(адрес):
    """
    Достаёт из адреса название улицы и приводит его к виду, пригодному
    для сравнения: набор слов без слова «улица», «проспект» и им подобных.

    Возвращает набор слов (например {"советской", "армии"}) либо None,
    если в адресе улицу распознать не удалось.

    Почему набор, а не строка: так порядок слов перестаёт иметь значение,
    и «улица Советской Армии» совпадёт с «Советской Армии улица».
    """
    for часть in (адрес or "").split(","):
        слова = _слова(часть)
        # Часть адреса считаем улицей, если в ней есть слово-тип улицы.
        if not any(слово in СЛОВА_ТИПОВ_УЛИЦ for слово in слова):
            continue
        название = [слово for слово in слова if слово not in СЛОВА_ТИПОВ_УЛИЦ]
        if название:
            return frozenset(название)
    return None


