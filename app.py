def скачать_фото(ссылка):
    """
    Живьём скачивает фотографию объявления. Ждём не дольше ТАЙМАУТ_ФОТО секунд.

    Возвращает содержимое файла либо None, если фотографии нет, сайт ответил
    отказом или не уложился в отведённое время. Ошибку наверх не поднимаем:
    одна не скачавшаяся картинка не должна срывать всю выгрузку.
    """
    if not ссылка:
        return None
    try:
        ответ = cffi.get(
            ссылка,
            headers=ЗАГОЛОВКИ_ФОТО,
            impersonate="chrome",
            timeout=ТАЙМАУТ_ФОТО,
        )
        if ответ.status_code != 200 or not ответ.content:
            return None
        return _в_понятный_word_формат(ответ.content)
    except Exception:
        return None


def _в_понятный_word_формат(картинка):
    """
    Word принимает jpeg и png, но не принимает webp. Обычно сайт присылает
    jpeg (см. ЗАГОЛОВКИ_ФОТО), но если всё-таки пришёл webp — узнаём его
    по первым байтам файла и пересохраняем.

    Для пересохранения нужна библиотека Pillow. Если её нет, просто
    возвращаем None — карточка соберётся без фотографии.
    """
    вебпэ = картинка[:4] == b"RIFF" and картинка[8:12] == b"WEBP"
    if not вебпэ:
        return картинка
    try:
        from PIL import Image
        снимок = Image.open(io.BytesIO(картинка)).convert("RGB")
        буфер = io.BytesIO()
        снимок.save(буфер, format="JPEG", quality=85)
        return буфер.getvalue()
    except Exception:
        return None


def _строка_документа(документ, ярлык, значение):
    """Абзац вида «Ярлык: значение», где ярлык выделен жирным."""
    абзац = документ.add_paragraph()
    жирный = абзац.add_run(f"{ярлык}: ")
    жирный.bold = True
    абзац.add_run(str(значение))
    return абзац


def собрать_документ_word(объект, площадь_объекта, аналоги, страницы_выдачи,
                          дата_объекта, дата_аналогов, с_фотографиями,
                          сообщать_о_ходе=None):
    """
    Собирает справку Word: шапка со сведениями об объекте и источниках,
    затем карточка на каждый аналог.

    Фотографии качаются живьём прямо во время сборки. Если какая-то не
    скачалась, карточка собирается без неё, а выгрузка продолжается.

    Возвращает пару: (файл как набор байтов, сколько фотографий не вышло).
    """
    документ = Document()

    # ── Шапка ────────────────────────────────────────────────────────────────
    документ.add_heading(f"{НАЗВАНИЕ_ИНСТРУМЕНТА}: подборка аналогов", level=0)

    сегодня = date.today().strftime("%d.%m.%Y")
    _строка_документа(документ, "Дата формирования", сегодня)
    _строка_документа(документ, "Аналогов в подборке", len(аналоги))

    документ.add_heading("Объект оценки", level=1)
    _строка_документа(
        документ, "Кадастровый номер",
        первое_заполненное(объект, "cad_num", "cad_number") or "—")
    _строка_документа(документ, "Адрес", объект.get("readable_address") or "—")
    _строка_документа(документ, "Площадь",
                      f"{кратко_площадь(площадь_объекта)} кв. м")
    _строка_документа(
        документ, "Назначение",
        первое_заполненное(объект, "permitted_use_established_by_document",
                           "purpose") or "—")
    _строка_документа(документ, "Кадастровая стоимость",
                      красиво_число(объект.get("cost_value"), "руб."))

    документ.add_heading("Источники данных", level=1)
    _строка_документа(
        документ, "Характеристики объекта",
        f"{ИСТОЧНИК_ОБЪЕКТА}. Дата обращения: "
        f"{дата_объекта.strftime('%d.%m.%Y')}")
    for номер, страница in enumerate(страницы_выдачи, start=1):
        подпись = ("Объявления" if len(страницы_выдачи) == 1
                   else f"Объявления, страница {номер}")
        _строка_документа(
            документ, подпись,
            f"{ИСТОЧНИК_АНАЛОГОВ}. Страница выдачи: {страница}. "
            f"Дата обращения: {дата_аналогов.strftime('%d.%m.%Y')}")

    оговорка = документ.add_paragraph()
    прогон = оговорка.add_run(ОГОВОРКА)
    прогон.italic = True
    прогон.font.size = Pt(10)
    прогон.font.color.rgb = RGBColor(0x60, 0x60, 0x60)

    # ── Карточки аналогов ────────────────────────────────────────────────────
    документ.add_heading("Аналоги", level=1)

    фото_не_вышло = 0

    for номер, аналог in enumerate(аналоги, start=1):
        документ.add_heading(f"Аналог {номер}. {аналог['Аналог']}", level=2)

        _строка_документа(документ, "Адрес", аналог["Адрес"] or "—")
        _строка_документа(документ, "Цена",
                          красиво_число(аналог["Цена, руб."], "руб."))

        площадь_и_этаж = f"{кратко_площадь(аналог['Площадь, кв. м'])} кв. м"
        if аналог["Этаж"]:
            площадь_и_этаж += f", этаж {аналог['Этаж']}"
        _строка_документа(документ, "Площадь и этаж", площадь_и_этаж)

        _строка_документа(документ, "Цена за кв. м",
                          красиво_число(аналог["Цена за кв. м, руб."], "руб."))
        _строка_документа(документ, "Совпадение адреса", аналог["Совпадение адреса"])

        if аналог.get("Текст объявления"):
            _строка_документа(документ, "Текст объявления",
                              аналог["Текст объявления"])

        # Партнёрские объявления уводят на сторонний сайт — помечаем.
        подпись_ссылки = аналог["Ссылка"]
        if аналог.get("Партнёрская площадка"):
            подпись_ссылки += " (партнерская площадка)"
        _строка_документа(документ, "Ссылка", подпись_ссылки)

        _строка_документа(документ, "Дата обращения",
                          дата_аналогов.strftime("%d.%m.%Y"))

        if с_фотографиями:
            картинка = скачать_фото(аналог.get("Фото"))
            if картинка:
                try:
                    документ.add_picture(io.BytesIO(картинка), width=Inches(4.5))
                    документ.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
                except Exception:
                    # Word не понял формат картинки — обходимся без неё.
                    фото_не_вышло += 1
            else:
                фото_не_вышло += 1

        if сообщать_о_ходе:
            сообщать_о_ходе(номер, len(аналоги))

    хранилище = io.BytesIO()
    документ.save(хранилище)
    return хранилище.getvalue(), фото_не_вышло


