def вырезать_данные_страницы(html):
    """
    Достаёт из текста страницы тот самый JSON, что лежит после надписи
    window.INITIAL_STATE = {...}.

    Просто найти последнюю «}» на странице нельзя: после данных идёт ещё много
    кода. Поэтому идём по тексту символ за символом и считаем фигурные скобки —
    открывающая прибавляет единицу, закрывающая отнимает. Как только счётчик
    вернулся к нулю, объект закончился.

    Отдельная тонкость: скобки, которые встречаются внутри текста в кавычках
    (например, в адресе объявления), считать нельзя — они не часть структуры.
    Поэтому помним, находимся ли мы сейчас внутри кавычек, и учитываем
    экранирование обратным слэшем (\\" — это кавычка внутри текста, а не конец
    текста).
    """
    начало_маркера = html.find(МАРКЕР_ДАННЫХ)
    if начало_маркера == -1:
        return None

    начало = html.find("{", начало_маркера)
    if начало == -1:
        return None

    глубина = 0          # сколько фигурных скобок сейчас открыто
    внутри_кавычек = False
    экранирование = False

    for позиция in range(начало, len(html)):
        символ = html[позиция]

        if внутри_кавычек:
            if экранирование:
                экранирование = False      # этот символ был экранирован, пропускаем
            elif символ == "\\":
                экранирование = True       # следующий символ — экранированный
            elif символ == '"':
                внутри_кавычек = False     # текст в кавычках закончился
            continue

        if символ == '"':
            внутри_кавычек = True
        elif символ == "{":
            глубина += 1
        elif символ == "}":
            глубина -= 1
            if глубина == 0:
                return html[начало:позиция + 1]

    return None  # скобки не закрылись — страница пришла обрезанной


def адрес_выдачи(город_на_сайте, сегмент, площадь, допуск_процентов, страница=1):
    """
    Собирает адрес страницы выдачи с фильтром по площади.

    Страницы на сайте нумеруются с единицы, причём первая отдаётся вообще без
    параметра page (значение page=1 вернуло бы первую страницу повторно),
    а вторая — с параметром page=2.

    Возвращает пару: (адрес страницы, (площадь от, площадь до)).
    """
    доля = допуск_процентов / 100
    площадь_от = max(1, round(площадь * (1 - доля)))
    площадь_до = round(площадь * (1 + доля))

    адрес = (
        f"https://realty.yandex.ru/{город_на_сайте}/{СЕГМЕНТЫ[сегмент]}/"
        f"?areaMin={площадь_от}&areaMax={площадь_до}"
    )
    if страница > 1:
        адрес += f"&page={страница}"

    return адрес, (площадь_от, площадь_до)


def прочитать_страницу(адрес_страницы):
    """
    Живой запрос одной страницы выдачи.
    Возвращает пару: (список объявлений как есть, всего страниц в выдаче).
    Если вместо выдачи показали капчу — поднимает исключение ПроверкаНаРобота.
    """
    ответ = cffi.get(
        адрес_страницы,
        headers=HEADERS_REALTY,
        impersonate="chrome",  # притворяемся настоящим Chrome на уровне TLS
        timeout=40,
    )

    if ответ.status_code != 200:
        raise ОшибкаСервера(
            f"Яндекс.Недвижимость ответила кодом {ответ.status_code}. "
            "Попробуйте повторить запрос через минуту."
        )

    сырые_данные = вырезать_данные_страницы(ответ.text)
    if сырые_данные is None:
        # Данных на странице нет — значит, вместо выдачи показали капчу.
        raise ПроверкаНаРобота()

    try:
        данные = json.loads(сырые_данные)
    except Exception:
        raise ПроверкаНаРобота()

    выдача = ((данные.get("search") or {}).get("offers") or {})
    объявления = выдача.get("entities") or []
    всего_страниц = ((выдача.get("pager") or {}).get("totalPages")) or 1

    return объявления, всего_страниц


def кратко_площадь(площадь):
    """
    Площадь для заголовка: 54.0 → «54», 53.6 → «53,6», 44.13 → «44,1».
    Лишний ноль после запятой в заголовке не нужен.
    """
    число = в_число(площадь)
    if число is None:
        return "—"
    текст = f"{число:.1f}".rstrip("0").rstrip(".")
    return текст.replace(".", ",")


def заголовок_аналога(объявление, сегмент, площадь, этаж):
    """
    Собирает короткое название аналога, например
    «2-комн. квартира, 54 кв. м, 4/9 эт.».

    Число комнат есть не всегда (у студий, офисов, домов его не указывают) —
    тогда пишем просто вид объекта по сегменту поиска.
    """
    комнат = объявление.get("roomsTotal")
    if сегмент == "Квартиры" and комнат:
        начало = f"{комнат}-комн. квартира"
    else:
        начало = СЕГМЕНТ_ЕДИНСТВЕННО.get(сегмент, "Объект")

    части = [начало, f"{кратко_площадь(площадь)} кв. м"]
    if этаж:
        части.append(f"{этаж} эт.")
    return ", ".join(части)


def обрезать_текст(текст, предел=ПРЕДЕЛ_ТЕКСТА_ОБЪЯВЛЕНИЯ):
    """
    Обрезает текст объявления по границе предложения и ставит многоточие.

    Режем не посреди слова: берём кусок нужной длины и отступаем назад
    до конца последнего целого предложения. Если предложение так и не
    закончилось — отступаем до последнего пробела.
    """
    текст = " ".join((текст or "").split())   # убираем лишние переводы строк
    if len(текст) <= предел:
        return текст

    кусок = текст[:предел]

    # Ищем последнюю точку, восклицательный или вопросительный знак.
    конец_предложения = max(кусок.rfind(". "), кусок.rfind("! "), кусок.rfind("? "))
    if конец_предложения > 0:
        return кусок[:конец_предложения + 1] + " …"

    последний_пробел = кусок.rfind(" ")
    if последний_пробел > 0:
        return кусок[:последний_пробел] + " …"
    return кусок + " …"


def партнёрская_площадка(ссылка):
    """
    Ведёт ли ссылка на сторонний сайт. Часть объявлений в выдаче
    партнёрские: щелчок по ним уводит не на Яндекс.Недвижимость,
    а на сайт агентства или застройщика.
    """
    домен = urlparse(ссылка or "").netloc.lower()
    return bool(домен) and домен != СВОЙ_ДОМЕН and not домен.endswith("." + СВОЙ_ДОМЕН)


def этаж_объявления(объявление):
    """
    Собирает этаж в привычном виде «4/9»: этаж объявления и всего этажей.
    У домов этаж объявления не указывают — тогда получится «—/2».
    """
    этажи = объявление.get("floorsOffered") or []
    всего = объявление.get("floorsTotal")

    на_каком = "–".join(str(э) for э in этажи) if этажи else "—"
    if всего in (None, ""):
        return на_каком if этажи else ""
    return f"{на_каком}/{всего}"


def запросить_аналоги(город_на_сайте, сегмент, площадь_объекта, допуск_процентов,
                      улица_объекта):
    """
    Читает до двух страниц выдачи, разбирает объявления и считает по каждому
    похожесть на объект оценки.

    Возвращает тройку:
      (список адресов прочитанных страниц, всего страниц в выдаче, аналоги).

    В каждом аналоге, кроме видимых в таблице колонок, лежат сведения для
    справки Word: текст объявления, ссылка на фотографию и признак
    партнёрской площадки.
    """
    адреса_страниц = []
    сырые_объявления = []
    всего_страниц = 1

    for номер_страницы in range(1, СТРАНИЦ_ЧИТАТЬ + 1):
        # После первой страницы уже знаем, сколько их всего: лишнее не читаем.
        if номер_страницы > всего_страниц:
            break

        адрес, _ = адрес_выдачи(
            город_на_сайте, сегмент, площадь_объекта, допуск_процентов,
            страница=номер_страницы,
        )
        объявления, всего_страниц = прочитать_страницу(адрес)

        адреса_страниц.append(адрес)
        сырые_объявления.extend(объявления)

    аналоги = []
    уже_видели = set()   # ссылки, которые уже попали в таблицу

    for объявление in сырые_объявления:
        цена = ((объявление or {}).get("price") or {}).get("value")
        площадь = ((объявление or {}).get("area") or {}).get("value")

        # Объявления без цены или без площади для подбора бесполезны.
        if not цена or not площадь:
            continue

        ссылка = объявление.get("url") or ""
        # Ссылки на сайте начинаются с «//» — дописываем протокол,
        # иначе ссылка не откроется.
        if ссылка.startswith("//"):
            ссылка = "https:" + ссылка

        # Одно и то же объявление попадается и на первой, и на второй
        # странице — второй раз в таблицу его не берём.
        if ссылка in уже_видели:
            continue
        уже_видели.add(ссылка)

        адрес_объявления = (объявление.get("location") or {}).get("geocoderAddress") or ""

        # Та же улица, что у объекта, или просто тот же город.
        улица_объявления = выделить_улицу(адрес_объявления)
        та_же_улица = (
            улица_объекта is not None
            and улица_объявления is not None
            and улица_объекта == улица_объявления
        )

        отклонение = (площадь - площадь_объекта) / площадь_объекта * 100
        этаж = этаж_объявления(объявление)

        # Ссылка на фотографию: берём первую из списка. Она, как и ссылка
        # на объявление, приходит начинающейся с «//» — дописываем протокол.
        фотографии = объявление.get("appLargeImages") or []
        фото = фотографии[0] if фотографии else None
        if фото and фото.startswith("//"):
            фото = "https:" + фото

        аналоги.append({
            "Аналог": заголовок_аналога(объявление, сегмент, площадь, этаж),
            "В расчёт": True,
            "Совпадение адреса": ТА_ЖЕ_УЛИЦА if та_же_улица else ТОТ_ЖЕ_ГОРОД,
            "Отклонение площади, %": round(отклонение, 1),
            "Цена, руб.": цена,
            "Площадь, кв. м": площадь,
            # Не округляем: в Excel эта же величина считается живой формулой
            # «цена делить на площадь», и итоги должны сходиться до копейки.
            "Цена за кв. м, руб.": цена / площадь,
            "Этаж": этаж,
            "Адрес": адрес_объявления,
            "Ссылка": ссылка,
            # Ниже — только для справки Word, в таблицу на экране не попадает.
            "Текст объявления": обрезать_текст(объявление.get("description")),
            "Фото": фото,
            "Партнёрская площадка": партнёрская_площадка(ссылка),
        })

    # Сортировка по похожести: сначала та же улица, потом просто тот же город;
    # внутри каждой группы — по близости площади к объекту.
    аналоги.sort(key=lambda а: (
        0 if а["Совпадение адреса"] == ТА_ЖЕ_УЛИЦА else 1,
        abs(а["Отклонение площади, %"]),
    ))

    return адреса_страниц, всего_страниц, аналоги


# ──────────────────────────── Выгрузка в Excel ───────────────────────────────
#
# Про формулы. Внутри файла .xlsx названия функций хранятся ТОЛЬКО
# по-английски — это устройство самого формата. Русский Excel показывает их
# по-русски сам: SUMPRODUCT вы увидите как СУММПРОИЗВ, IFERROR — как
# ЕСЛИОШИБКА. Если записать в файл русское название, Excel открыть формулу
# не сможет и покажет ошибку #ИМЯ?. Поэтому ниже они по-английски.

# Форматы чисел. Внутри файла разряды всегда пишутся запятой, а дробная часть
# точкой — Excel сам переводит это в привычный русский вид «1 234 567,89».
ФОРМАТ_ДЕНЕГ = '#,##0.00" ₽"'
ФОРМАТ_ПЛОЩАДИ = '#,##0.00'
ФОРМАТ_ПРОЦЕНТОВ = '0.0'
ФОРМАТ_ВЕСА = '0.00'

ЗАЛИВКА_ШАПКИ = PatternFill("solid", fgColor="DDEBF7")
ЖИРНЫЙ = Font(bold=True)
ТОНКАЯ_ЛИНИЯ = Side(style="thin", color="B0B0B0")
РАМКА = Border(left=ТОНКАЯ_ЛИНИЯ, right=ТОНКАЯ_ЛИНИЯ,
               top=ТОНКАЯ_ЛИНИЯ, bottom=ТОНКАЯ_ЛИНИЯ)


def _обычное_значение(значение):
    """
    Числа из таблицы приходят в виде особых типов библиотеки pandas.
    Excel их не понимает, поэтому превращаем в обычные число или строку.
    """
    if значение is None:
        return None
    if hasattr(значение, "item"):     # признак числа из pandas
        return значение.item()
    return значение


def _оформить_шапку(лист, номер_строки, заголовки):
    """Пишет строку заголовков таблицы и делает её заметной."""
    for номер_колонки, заголовок in enumerate(заголовки, start=1):
        ячейка = лист.cell(row=номер_строки, column=номер_колонки, value=заголовок)
        ячейка.font = ЖИРНЫЙ
        ячейка.fill = ЗАЛИВКА_ШАПКИ
        ячейка.border = РАМКА
        ячейка.alignment = Alignment(horizontal="center", vertical="center",
                                     wrap_text=True)


def _ширины(лист, ширины_колонок):
    """Задаёт ширину колонок, чтобы текст не приходилось раздвигать руками."""
    for номер_колонки, ширина in enumerate(ширины_колонок, start=1):
        лист.column_dimensions[get_column_letter(номер_колонки)].width = ширина


def лист_аналоги(книга, таблица):
    """
    Лист «Аналоги» — объявления как есть: всё, что видно на экране,
    включая адрес, этаж, совпадение адреса и ссылку.
    """
    лист = книга.active
    лист.title = "Аналоги"

    заголовки = list(таблица.columns)
    _оформить_шапку(лист, 1, заголовки)

    for сдвиг, (_, строка) in enumerate(таблица.iterrows()):
        номер_строки = 2 + сдвиг
        for номер_колонки, имя in enumerate(заголовки, start=1):
            значение = _обычное_значение(строка[имя])

            # Галочку показываем словами — так понятнее в таблице.
            if имя == "В расчёт":
                значение = "да" if значение else "нет"

            ячейка = лист.cell(row=номер_строки, column=номер_колонки, value=значение)
            ячейка.border = РАМКА

            if имя in ("Цена, руб.", "Цена за кв. м, руб."):
                ячейка.number_format = ФОРМАТ_ДЕНЕГ
            elif имя == "Площадь, кв. м":
                ячейка.number_format = ФОРМАТ_ПЛОЩАДИ
            elif имя == "Отклонение площади, %":
                ячейка.number_format = ФОРМАТ_ПРОЦЕНТОВ
            elif имя == "Ссылка" and значение:
                # Делаем ссылку кликабельной прямо из Excel.
                ячейка.hyperlink = значение
                ячейка.style = "Hyperlink"

    # Ширины под порядок колонок из КОЛОНКИ_НА_ЭКРАНЕ.
    _ширины(лист, [38, 9, 18, 14, 16, 14, 18, 10, 52, 46])
    лист.freeze_panes = "A2"   # шапка не уезжает при прокрутке
    return лист


def лист_расчет(книга, объект, площадь_объекта, включённые):
    """
    Лист «Расчёт»: шапка со сведениями об объекте, таблица аналогов
    с живыми формулами и итог внизу.

    Все итоговые числа — формулы, а не вставленные значения. Поэтому,
    если поправить корректировку или вес прямо в Excel, средневзвешенная
    цена и ориентир стоимости пересчитаются сами.
    """
    лист = книга.create_sheet("Расчёт")

    # ── Шапка: сведения об объекте оценки ────────────────────────────────────
    заголовок = лист.cell(row=1, column=1,
                          value="Расчёт стоимости объекта сравнительным подходом")
    заголовок.font = Font(bold=True, size=14)

    СТРОКА_НОМЕРА, СТРОКА_АДРЕСА = 3, 4
    СТРОКА_ПЛОЩАДИ, СТРОКА_СТОИМОСТИ = 5, 6

    сведения = [
        (СТРОКА_НОМЕРА, "Кадастровый номер",
         первое_заполненное(объект, "cad_num", "cad_number") or "—", None),
        (СТРОКА_АДРЕСА, "Адрес",
         объект.get("readable_address") or "—", None),
        (СТРОКА_ПЛОЩАДИ, "Площадь объекта, кв. м",
         float(площадь_объекта), ФОРМАТ_ПЛОЩАДИ),
        (СТРОКА_СТОИМОСТИ, "Кадастровая стоимость",
         в_число(объект.get("cost_value")), ФОРМАТ_ДЕНЕГ),
    ]
    for номер_строки, подпись, значение, формат in сведения:
        ячейка_подписи = лист.cell(row=номер_строки, column=1, value=подпись)
        ячейка_подписи.font = ЖИРНЫЙ
        ячейка_значения = лист.cell(row=номер_строки, column=2, value=значение)
        if формат:
            ячейка_значения.number_format = формат

    # ── Таблица аналогов ─────────────────────────────────────────────────────
    СТРОКА_ШАПКИ = 8
    ПЕРВАЯ_СТРОКА = СТРОКА_ШАПКИ + 1

    _оформить_шапку(лист, СТРОКА_ШАПКИ, [
        "№",
        "Адрес аналога",
        "Цена, руб.",
        "Площадь, кв. м",
        "Цена за кв. м, руб.",
        "Корректировка, %",
        "Скорректированная цена за кв. м, руб.",
        "Вес аналога",
    ])

    for сдвиг, (_, аналог) in enumerate(включённые.iterrows()):
        строка = ПЕРВАЯ_СТРОКА + сдвиг

        лист.cell(row=строка, column=1, value=сдвиг + 1)
        лист.cell(row=строка, column=2, value=аналог["Адрес"])

        ячейка_цены = лист.cell(row=строка, column=3,
                                value=_обычное_значение(аналог["Цена, руб."]))
        ячейка_цены.number_format = ФОРМАТ_ДЕНЕГ

        ячейка_площади = лист.cell(row=строка, column=4,
                                   value=_обычное_значение(аналог["Площадь, кв. м"]))
        ячейка_площади.number_format = ФОРМАТ_ПЛОЩАДИ

        # Цена за квадратный метр — формула «цена делить на площадь».
        ячейка_за_метр = лист.cell(row=строка, column=5, value=f"=C{строка}/D{строка}")
        ячейка_за_метр.number_format = ФОРМАТ_ДЕНЕГ

        # Поле для вашей корректировки. По умолчанию ноль — правьте руками.
        ячейка_корректировки = лист.cell(row=строка, column=6, value=0)
        ячейка_корректировки.number_format = ФОРМАТ_ПРОЦЕНТОВ

        # Скорректированная цена: цена за метр с учётом корректировки.
        ячейка_скорректированной = лист.cell(
            row=строка, column=7, value=f"=E{строка}*(1+F{строка}/100)")
        ячейка_скорректированной.number_format = ФОРМАТ_ДЕНЕГ

        # Вес аналога. По умолчанию единица — все аналоги равнозначны.
        ячейка_веса = лист.cell(row=строка, column=8, value=1)
        ячейка_веса.number_format = ФОРМАТ_ВЕСА

        for номер_колонки in range(1, 9):
            лист.cell(row=строка, column=номер_колонки).border = РАМКА

    ПОСЛЕДНЯЯ_СТРОКА = ПЕРВАЯ_СТРОКА + len(включённые) - 1

    # ── Итог: средневзвешенная цена и ориентир стоимости ─────────────────────
    СТРОКА_СРЕДНЕЙ = ПОСЛЕДНЯЯ_СТРОКА + 2
    СТРОКА_ОРИЕНТИРА = СТРОКА_СРЕДНЕЙ + 1

    итоги = [
        (
            СТРОКА_СРЕДНЕЙ,
            "Средневзвешенная цена за кв. м",
            # СУММПРОИЗВ перемножает скорректированные цены на веса и складывает,
            # затем делим на сумму весов. ЕСЛИОШИБКА страхует от нулевых весов.
            f"=IFERROR(SUMPRODUCT(G{ПЕРВАЯ_СТРОКА}:G{ПОСЛЕДНЯЯ_СТРОКА},"
            f"H{ПЕРВАЯ_СТРОКА}:H{ПОСЛЕДНЯЯ_СТРОКА})"
            f"/SUM(H{ПЕРВАЯ_СТРОКА}:H{ПОСЛЕДНЯЯ_СТРОКА}),\"\")",
        ),
        (
            СТРОКА_ОРИЕНТИРА,
            "Ориентир стоимости объекта",
            # Средневзвешенная цена умножается на площадь объекта из шапки листа.
            f"=G{СТРОКА_СРЕДНЕЙ}*B{СТРОКА_ПЛОЩАДИ}",
        ),
    ]

    for номер_строки, подпись, формула in итоги:
        лист.merge_cells(start_row=номер_строки, start_column=1,
                         end_row=номер_строки, end_column=6)
        ячейка_подписи = лист.cell(row=номер_строки, column=1, value=подпись)
        ячейка_подписи.font = ЖИРНЫЙ
        ячейка_подписи.alignment = Alignment(horizontal="right")

        ячейка_итога = лист.cell(row=номер_строки, column=7, value=формула)
        ячейка_итога.font = ЖИРНЫЙ
        ячейка_итога.fill = ЗАЛИВКА_ШАПКИ
        ячейка_итога.border = РАМКА
        ячейка_итога.number_format = ФОРМАТ_ДЕНЕГ

    пояснение = лист.cell(
        row=СТРОКА_ОРИЕНТИРА + 2, column=1,
        value="Правьте корректировки в колонке «Корректировка, %» "
              "и веса в колонке «Вес аналога» — итоги пересчитаются сами. "
              "Корректировка пишется в процентах: −10 означает минус 10 %.",
    )
    пояснение.font = Font(italic=True, color="666666")

    _ширины(лист, [6, 48, 18, 16, 22, 16, 24, 12])
    лист.freeze_panes = f"A{ПЕРВАЯ_СТРОКА}"
    return лист


