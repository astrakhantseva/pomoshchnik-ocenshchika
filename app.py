def очистить_номер(текст):
    """
    Убирает все пробелы из кадастрового номера, чтобы сравнивать номера
    одинаково: «77:01:0001001:1234» и « 77:01:0001001:1234 » — это одно и то же.
    """
    return "".join(str(текст or "").split())


def первое_заполненное(словарь, *имена_полей):
    """
    Возвращает значение первого поля из перечисленных, которое реально
    заполнено. Нужно потому, что нужные сведения лежат в разных полях
    в зависимости от вида объекта (участок, здание, помещение).
    """
    for имя in имена_полей:
        значение = словарь.get(имя)
        if значение not in (None, "", []):
            return значение
    return None


def в_число(значение):
    """
    Аккуратно превращает значение в число. Площадь может прийти строкой
    вида «50,9» — запятую заменяем на точку. Если не получилось — None.
    """
    if значение is None:
        return None
    try:
        return float(str(значение).replace(" ", "").replace(",", "."))
    except (TypeError, ValueError):
        return None


def красиво_число(значение, единица=""):
    """
    Превращает число в привычный для отчёта вид: 1234567.89 → «1 234 567,89».
    Если значение не число — показывает его как есть.
    """
    число = в_число(значение)
    if число is None:
        return "нет данных" if значение is None else str(значение)
    # Сначала формат по-английски (1,234,567.89), затем меняем разделители
    # на русские: запятая → пробел, точка → запятая.
    текст = f"{число:,.2f}".replace(",", " ").replace(".", ",")
    return f"{текст} {единица}".strip()


